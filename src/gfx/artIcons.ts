export function icon12(key: string): PC {
  const p = new PC(12, 12);
  p.rect(0, 0, 12, 12, BLACK);
  p.px(0, 0, -1);
  p.px(11, 0, -1);
  p.px(0, 11, -1);
  p.px(11, 11, -1);
  const rows = (ICONS10[key] ?? ICONS10.w_unknown).trim().split('\n');
  parse(rows, p, 1, 1);
  return p;
}

export function icon7(key: string): PC {
  const p = new PC(7, 7);
  p.rect(0, 0, 7, 7, BLACK);
  parse((ICONS5[key] ?? ICONS5.s_hex).split(' '), p, 1, 1);
  return p;
}

/** Variant for status chips on the boss: marks "debuff" with a mid-grey frame. */
export function icon7framed(key: string): PC {
  const p = new PC(9, 9);
  p.rect(0, 0, 9, 9, MID);
  p.blit(icon7(key), 1, 1);
  return p;
}

