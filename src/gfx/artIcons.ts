function parse(rows: string[], into: PC, ox: number, oy: number) {
  rows.forEach((r, y) => {
    for (let x = 0; x < r.length; x++) {
      const ch = r[x];
      if (ch === '4') into.px(ox + x, oy + y, WHITE);
      else if (ch === '3') into.px(ox + x, oy + y, 3);
      else if (ch === '0') into.px(ox + x, oy + y, BLACK);
    }
  });
}

